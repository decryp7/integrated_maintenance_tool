def lines(f):
    return open(os.path.join(S, f), encoding="utf-8", errors="replace").read().splitlines()


def window(f, start, n):
    return lines(f)[start:start + n]


def count(f, start, n, needle):
    return sum(1 for l in window(f, start, n) if needle in l)


def q(s):
    return json.dumps(s, ensure_ascii=False)


def arr(xs):
    return "[" + ", ".join(q(x) for x in xs) + "]"


def lit(s):  # TOML multi-line literal string
    return "'''\n" + s + "\n'''"


out = []


def case(section, **kw):
    out.append(f"[[{section}]]")
    for k, v in kw.items():
        if isinstance(v, list):
            out.append(f"{k} = {arr(v)}")
        elif isinstance(v, bool):
            out.append(f"{k} = {'true' if v else 'false'}")
        elif isinstance(v, int):
            out.append(f"{k} = {v}")
        elif isinstance(v, tuple):  # raw text block
            out.append(f"{k} = {lit(v[0])}")
        else:
            out.append(f"{k} = {q(v)}")
    out.append("")


out.append("# Evaluation cases built from /samples. Generated by evals/make_cases.py; expectations are computed from the data.")
out.append("# Run with: cargo run --release -p imt-ai --example eval -- --model <file.gguf>")
out.append("")

