import { expect, test } from '@playwright/test';
import { expectNoSeriousViolations } from './axe';
import { openAiApp, runCommand } from './ai-support';

test.describe('incident summary report', () => {
  test('builds the summary with an AI-written narrative that is clearly marked', async ({ page }, testInfo) => {
    await openAiApp(page);
    await runCommand(page, 'Report: Incident summary…');
    const dialog = page.getByRole('dialog', { name: 'Incident summary' });
    await expect(dialog.getByText('The engine computes every number and event in the report')).toBeVisible();
    await expect(dialog.getByRole('checkbox', { name: 'Add an AI narrative' })).toBeChecked();
    await expectNoSeriousViolations(page, testInfo, 'incident-dialog');
    await dialog.getByRole('button', { name: 'Build', exact: true }).click();

    const view = page.locator('imt-report-view');
    await expect(view).toBeVisible();
    await expect(view.locator('blockquote').filter({ hasText: 'AI-written narrative. Generated by the local model from the facts below; check the cited events.' })).toBeVisible();
    await expect(view.getByRole('region', { name: 'Section Narrative (AI-written)' })).toBeVisible();
    await expect(view.getByRole('region', { name: 'Section Summary' })).toBeVisible();
  });

  test('without a model the narrative is disabled and the report still builds', async ({ page }) => {
    await openAiApp(page, 'mockAi=setup');
    await runCommand(page, 'Report: Incident summary…');
    const dialog = page.getByRole('dialog', { name: 'Incident summary' });
    await expect(dialog.getByRole('checkbox', { name: 'Add an AI narrative' })).toBeDisabled();
    await expect(dialog.getByText('Needs an AI model')).toBeVisible();
    await dialog.getByRole('button', { name: 'Build', exact: true }).click();
    const view = page.locator('imt-report-view');
    await expect(view.getByRole('region', { name: 'Section Summary' })).toBeVisible();
    await expect(view.getByRole('region', { name: 'Section Narrative (AI-written)' })).toHaveCount(0);
  });
});
