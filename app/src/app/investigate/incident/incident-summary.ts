import { computed, inject, Injectable, signal } from '@angular/core';
import type { Narrative } from '../../ai/ai.types';
import { toAiError } from '../../ai/ai-backend';
import { AiStatusStore } from '../../ai/ai-status.store';
import { TimeCursor } from '../../analysis/time-cursor';
import { IncidentRequest, IssueMatch, Report, ReportSection } from '../../core/api.types';
import { ReportStore } from '../../share/report/report.store';
import { newSection, withId } from '../../share/report/report-model';
import { IncidentBackend } from '../investigate-backend';
import { KnownIssuesStore } from '../known-issues/known-issues.store';

export const DEFAULT_TOP = 5;
export const MAX_TOP = 10;

/** Clamps the ranking size to 1..10; anything that is not a number gives the default. */
export function clampTop(value: unknown): number {
  const n = Math.round(Number(value));
  return Number.isFinite(n) ? Math.min(MAX_TOP, Math.max(1, n)) : DEFAULT_TOP;
}

/** The marker line that opens the narrative: it must always be clear that a model wrote it. */
export const AI_MARKER = 'AI-written narrative. Generated by the local model from the facts below; check the cited events.';

/** The markdown of the narrative block: the marker, the text, and a note on citations the engine could not verify. */
export function narrativeMarkdown(narrative: Narrative): string {
  const unverified = narrative.citations.flatMap((c) => (c.kind === 'record' && !c.verified ? [c.id] : []));
  const note = unverified.length ? `\n\nUnverified citations: ${unverified.map((id) => `#${id}`).join(', ')}` : '';
  return `> ${AI_MARKER}\n\n${narrative.text.trim()}${note}`;
}

/** The label that marks a known issue the AI suggested and the engine verified on the open data. */
export const AI_ISSUE_MARKER = 'AI suggested, verified by the engine';

/** The report section for the accepted AI known-issue suggestions: one finding and its evidence per issue. */
export function acceptedIssuesSection(matches: readonly IssueMatch[]): ReportSection {
  return {
    ...newSection($localize`:@@incident.acceptedIssuesTitle:Known issues (accepted AI suggestions)`),
    blocks: matches.flatMap((m) => [
      withId({ type: 'finding', severity: 'warning', title: m.issue.title, detail: `${AI_ISSUE_MARKER}. ${m.issue.fix} (${m.count} events, from ${m.issue.file})` }),
      ...(m.sampleIds.length ? [withId({ type: 'events', caption: m.query, ids: m.sampleIds })] : []),
    ]),
  };
}

/**
 * The incident summary dialog's state: the engine builds the report (adopted as the active one); the optional AI
 * narrative is added afterwards as the first section, and its failure never fails the report.
 */
@Injectable({ providedIn: 'root' })
export class IncidentSummary {
  private readonly backend = inject(IncidentBackend);
  private readonly reports = inject(ReportStore);
  private readonly ai = inject(AiStatusStore);
  private readonly cursor = inject(TimeCursor);
  private readonly issues = inject(KnownIssuesStore);

  readonly title = signal($localize`:@@incident.defaultTitle:Incident summary`);
  readonly top = signal(DEFAULT_TOP);
  readonly narrativeWanted = signal(true);
  readonly building = signal(false);
  /** Why the report could not be built. */
  readonly error = signal<string | null>(null);
  /** The report was built but the narrative could not be added (and why). */
  readonly narrativeError = signal<string | null>(null);
  /** The report built by the last run (its narrative may be missing). */
  readonly built = signal<Report | null>(null);

  readonly hasModel = computed(() => this.ai.hasModel());
  /** The time range the report covers: the current selection, or all data. */
  readonly period = computed(() => this.cursor.selection());
  readonly request = computed<IncidentRequest>(() => {
    const p = this.period();
    return { title: this.title().trim() || undefined, from: p?.from ?? null, to: p?.to ?? null, top: clampTop(this.top()) };
  });

  setTop(value: unknown): void {
    this.top.set(clampTop(value));
  }

  /** Builds the report and (when wanted and possible) its narrative. Resolves true when the report exists. */
  async build(): Promise<boolean> {
    if (this.building()) return false;
    this.building.set(true);
    this.error.set(null);
    this.narrativeError.set(null);
    this.built.set(null);
    try {
      const report = this.reports.adopt(await this.backend.build(this.request()));
      this.built.set(report);
      const accepted = this.issues.acceptedSuggestions();
      if (accepted.length) this.reports.appendSection(report.id, acceptedIssuesSection(accepted));
      if (this.narrativeWanted() && this.hasModel()) await this.addNarrative();
      return true;
    } catch (e) {
      this.error.set(toAiError(e).message);
      return false;
    } finally {
      this.building.set(false);
    }
  }

  /** Adds (or retries) the narrative of the built report; a failure is reported, not thrown. */
  async addNarrative(): Promise<boolean> {
    const report = this.built();
    if (!report) return false;
    this.narrativeError.set(null);
    try {
      const narrative = await this.backend.narrative(report);
      const section: ReportSection = {
        ...newSection($localize`:@@incident.narrativeTitle:Narrative (AI-written)`),
        blocks: [withId({ type: 'text', markdown: narrativeMarkdown(narrative) })],
      };
      this.reports.prependSection(report.id, section);
      this.built.set(null);
      return true;
    } catch (e) {
      const err = toAiError(e);
      this.narrativeError.set(
        err.code === 'noModel'
          ? $localize`:@@incident.noModelError:No AI model is set up. Install one in Settings > AI, then retry. ${err.message}:reason:`
          : err.message,
      );
      return false;
    }
  }
}
