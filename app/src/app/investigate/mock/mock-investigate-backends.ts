/** Browser stand-in for playbooks: an in-memory library, steps counted by a text search of the mock workspace. */
export class MockPlaybookBackend implements PlaybookBackend {
  private readonly saved = new Map<string, Playbook>();
  constructor(private readonly imt: ImtBackend) {}

  async library(): Promise<PlaybookLibrary> {
    return { playbooks: [...this.saved.values()], templates: TEMPLATES, warnings: [] };
  }
  async save(playbook: Playbook): Promise<Playbook> {
    if (!/^[a-z0-9]+(-[a-z0-9]+)*$/.test(playbook.id)) throw new CmdError({ code: 'invalid', message: 'the playbook id must be lowercase letters, digits or dashes', retryable: false });
    this.saved.set(playbook.id, playbook);
    return playbook;
  }
  async remove(id: string): Promise<boolean> {
    return this.saved.delete(id);
  }
  async importFile(): Promise<Playbook> {
    return TEMPLATES[0];
  }
  async exportFile(): Promise<void> {}

  async runStep(step: PlaybookStep): Promise<PlaybookStepResult> {
    const plain = (status: PlaybookStepResult['status'], summary: string): PlaybookStepResult => ({ status, summary, count: null, sampleIds: [], columns: [], rows: [] });
    const a = step.action;
    if (a.type === 'manual') return plain('info', 'Do this by hand, then mark it done.');
    if (a.type === 'openView') return plain('info', `Open the ${a.view} view.`);
    const word = /level\s*=\s*fatal/.test(a.ql) ? 'fatal' : /error/.test(a.ql) ? 'error' : 'timed out';
    const m = await matching(this.imt, word);
    const base = { count: m.count, sampleIds: m.ids, columns: [], rows: [] };
    if (a.type === 'check') {
      const ok = a.expect.kind === 'noMatch' ? m.count === 0 : a.expect.kind === 'anyMatch' ? m.count > 0 : a.expect.kind === 'atLeast' ? m.count >= a.expect.n : m.count <= a.expect.n;
      return { ...base, status: ok ? 'pass' : 'fail', summary: `Expected ${a.expect.kind}, found ${m.count}.` };
    }
    return { ...base, status: 'info', summary: a.type === 'filter' ? `The filter matches ${m.count} events.` : `Found ${m.count} events.` };
  }
  async start(playbook: Playbook, runId: string): Promise<PlaybookRun> {
    if (!runId.trim()) throw new CmdError({ code: 'invalid', message: 'a run needs an id', retryable: false });
    return { id: runId, playbook, startedAt: Date.now(), steps: [] };
  }
  async record(run: PlaybookRun, stepId: string, result: PlaybookStepResult, note: string): Promise<PlaybookRun> {
    if (!run.playbook.steps.some((s) => s.id === stepId)) throw new CmdError({ code: 'invalid', message: `the playbook has no step "${stepId}"`, retryable: false });
    const rec = { stepId, status: result.status, summary: result.summary, count: result.count, sampleIds: result.sampleIds, note, at: Date.now() };
    return { ...run, steps: [...run.steps.filter((r) => r.stepId !== stepId), rec] };
  }
  async restore(record: unknown): Promise<PlaybookRestore> {
    const r = record as { version?: number; runs?: PlaybookRun[] } | null;
    if (!r || r.version !== 1 || !Array.isArray(r.runs)) return { record: { version: 1, runs: [] }, warnings: r ? ['the saved playbook runs are damaged and were not restored'] : [] };
    return { record: { version: 1, runs: r.runs }, warnings: [] };
  }
}
