/** Events of the mock workspace that contain `text` (a stand-in for a pattern or a query). */
async function matching(imt: ImtBackend, text: string): Promise<{ count: number; ids: number[] }> {
  const page = await imt.queryPage({ query: { text, regex: false }, offset: 0, limit: 5, descending: false } as never);
  return { count: page.total, ids: page.rows.map((r) => r.id) };
}

/**
 * Browser stand-in for known-issue matching: one issue "declared" in a sample knowledge file, matched by a text
 * search of the mock workspace. Plausible, never the reference: the engine is.
 */
export class MockKnownIssuesBackend implements KnownIssuesBackend {
  /** Whether the mock has a model (tests and e2e set this to exercise the no-model path). */
  static hasModel = true;
  constructor(private readonly imt: ImtBackend) {}

  async match(): Promise<IssueReport> {
    const m = await matching(this.imt, 'timed out');
    const matches: IssueMatch[] =
      m.count > 0
        ? [
            {
              issue: { id: 'payment-gateway-timeouts', title: 'Payment gateway timeouts', fix: 'Raise the gateway timeout to 30 s and check the provider status page.', matcher: { type: 'pattern', pattern: '(?i)timed out' }, file: 'Payments' },
              origin: 'rule',
              query: '@message ~ "(?i)timed out" or @exception ~ "(?i)timed out"',
              count: m.count,
              sampleIds: m.ids,
            },
          ]
        : [];
    return { matches, checked: 2, truncated: 0, warnings: ['Payments, known issue 2: it needs a `fix:`'] };
  }

  async suggest(): Promise<IssueMatch[]> {
    if (!MockKnownIssuesBackend.hasModel) throw new AiError('noModel', 'No AI model is installed. Set one up in Settings > AI.');
    const m = await matching(this.imt, 'refused');
    return m.count
      ? [
          {
            issue: { id: 'ai-connection-refused', title: 'Connection refused', fix: 'Check that the service is listening and the firewall allows the port.', matcher: { type: 'query', ql: 'message contains "refused"' }, file: 'Operations' },
            origin: 'ai',
            query: 'message contains "refused"',
            count: m.count,
            sampleIds: m.ids,
          },
        ]
      : [];
  }
}

/** Browser stand-in for the incident summary: a small report from the mock workspace's summary. */
export class MockIncidentBackend implements IncidentBackend {
  constructor(private readonly imt: ImtBackend) {}

  async build(request: IncidentRequest): Promise<Report> {
    const s = await this.imt.workspaceSummary();
    const errors = await matching(this.imt, 'error');
    const now = Date.now();
    return {
      version: 1,
      id: `incident-${now}`,
      title: request.title?.trim() || 'Incident summary',
      summary: `${s.total} events, ${s.sources.length} sources; generated by the engine from the open data.`,
      createdAt: now,
      updatedAt: now,
      sections: [
        { id: 's1', title: 'Summary', blocks: [{ id: 'b1', type: 'text', markdown: `**Events:** ${s.total}  \n**Sources:** ${s.sources.length}` }] },
        { id: 's2', title: 'Top problems', blocks: [{ id: 'b2', type: 'finding', severity: 'warning', title: `${errors.count} events mention an error`, detail: 'Counted by the mock engine.' }, { id: 'b3', type: 'events', caption: 'Evidence', ids: errors.ids }] },
      ],
    };
  }

  async narrative(report: Report): Promise<Narrative> {
    if (!MockKnownIssuesBackend.hasModel) throw new AiError('noModel', 'No AI model is installed. Set one up in Settings > AI.');
    const id = report.sections.flatMap((s) => s.blocks).flatMap((b) => (b.type === 'events' ? b.ids : []))[0];
    const text = id === undefined ? 'Nothing in the report to narrate.' : `The report shows failures (event ${id}). Check the evidence before relying on this summary.`;
    return {
      text,
      citations: id === undefined ? [] : [{ kind: 'record', id, verified: true }],
      evidence: { recordIds: id === undefined ? [] : [id], queries: [] },
      usage: { inputTokens: 0, outputTokens: 0 },
    };
  }
}

