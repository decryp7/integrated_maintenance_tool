/** The id of every registered dialog. */
export type DialogId = (typeof DIALOG_DEFS)[number]['id'];

/** What dialog `I` resolves to when it closes with an answer. */
export type DialogResultOf<I extends DialogId> = Exclude<Extract<(typeof DIALOG_DEFS)[number], { id: I }>['_result'], undefined>;

const BY_ID = new Map<string, DialogDef>(DIALOG_DEFS.map((d) => [d.id, d as unknown as DialogDef]));

/** The definition of dialog `id`. */
export function dialogDef(id: string): DialogDef | undefined {
  return BY_ID.get(id);
}

/** Where the dialog shell finds definitions (tests provide their own). */
export const DIALOG_LOOKUP = new InjectionToken<(id: string) => DialogDef | undefined>('DIALOG_LOOKUP', { providedIn: 'root', factory: () => dialogDef });
