// Run: node --test scripts/whats-new.test.mjs
import assert from 'node:assert/strict';
import { mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { test } from 'node:test';
import { CHANGELOG_PATH, generate, OUTPUT_PATH, parseChangelog, render } from './whats-new.mjs';

const MD = `# Changelog

## Unreleased

### Added

- not shown

## 1.2.0 (2026-11-01)

### Added

- **Shortcuts:** edit keys
* second

### Fixed

### Empty

## v1.1.0

### Changed

- older
`;

test('reads releases, groups and items, skipping Unreleased and empty groups', () => {
  assert.deepEqual(parseChangelog(MD), [
    { version: '1.2.0', date: '2026-11-01', groups: [{ title: 'Added', items: ['Shortcuts: edit keys', 'second'] }] },
    { version: '1.1.0', date: '', groups: [{ title: 'Changed', items: ['older'] }] },
  ]);
});

test('garbage in gives an empty list, never a throw', () => {
  assert.deepEqual(parseChangelog(undefined), []);
  assert.deepEqual(parseChangelog('### Added\n- orphan\n'), []);
});

test('the committed generated module is up to date with CHANGELOG.md', () => {
  assert.equal(generate({ check: true, changelog: CHANGELOG_PATH, output: OUTPUT_PATH }), true);
  assert.match(readFileSync(OUTPUT_PATH, 'utf8'), /^\/\/ Generated by scripts\/whats-new\.mjs/);
});

test('writes the module, reports staleness in check mode and tolerates a missing changelog', () => {
  const dir = mkdtempSync(join(tmpdir(), 'whatsnew-'));
  const changelog = join(dir, 'CHANGELOG.md');
  const output = join(dir, 'out.ts');
  writeFileSync(changelog, MD);
  assert.equal(generate({ check: true, changelog, output }), false);
  assert.equal(generate({ changelog, output }), true);
  assert.equal(readFileSync(output, 'utf8'), render(parseChangelog(MD)));
  assert.equal(generate({ check: true, changelog, output }), true);
  assert.equal(generate({ changelog: join(dir, 'missing.md'), output }), true);
  assert.match(readFileSync(output, 'utf8'), /= \[\];/);
});

test('the changelog uses the product name, never the old one', () => {
  assert.doesNotMatch(readFileSync(CHANGELOG_PATH, 'utf8'), /\bIMT\b/);
  assert.doesNotMatch(readFileSync(OUTPUT_PATH, 'utf8'), /\bIMT\b/);
});
