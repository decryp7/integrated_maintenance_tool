#!/usr/bin/env node
// Turns CHANGELOG.md (repository root) into src/app/whats-new/changelog.generated.ts, the data behind the "What's new"
// panel. Run by `npm run build` / `npm start`; `--check` fails when the committed file is stale (used by the node tests).
//
// Format read: `## <version> (<date>)` per release, `### <Group>` per group, `- item` per entry (git-cliff's output
// shape too). `## Unreleased` and anything before the first release heading is ignored.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
export const CHANGELOG_PATH = resolve(here, '../../CHANGELOG.md');
export const OUTPUT_PATH = resolve(here, '../src/app/whats-new/changelog.generated.ts');

const RELEASE = /^##\s+v?(\d+\.\d+\.\d+(?:[-+][0-9A-Za-z.-]+)?)(?:\s+\((\d{4}-\d{2}-\d{2})\))?\s*$/;

/** Parses the changelog into releases, newest first as written. Unknown lines are ignored; never throws. */
export function parseChangelog(markdown) {
  const releases = [];
  let release = null;
  let group = null;
  for (const raw of String(markdown).split(/\r?\n/)) {
    const line = raw.trimEnd();
    if (line.startsWith('## ')) {
      const m = RELEASE.exec(line);
      release = m ? { version: m[1], date: m[2] ?? '', groups: [] } : null;
      group = null;
      if (release) releases.push(release);
    } else if (release && line.startsWith('### ')) {
      group = { title: line.slice(4).trim(), items: [] };
      release.groups.push(group);
    } else if (release && group && /^[-*]\s+/.test(line)) {
      const item = line.replace(/^[-*]\s+/, '').replace(/\*\*/g, '').trim();
      if (item) group.items.push(item);
    }
  }
  for (const r of releases) r.groups = r.groups.filter((g) => g.items.length > 0);
  return releases;
}

/** The generated TypeScript module for `releases`. */
export function render(releases) {
  return (
    '// Generated by scripts/whats-new.mjs from CHANGELOG.md. Do not edit.\n' +
    "import { ChangelogRelease } from './changelog';\n\n" +
    `export const CHANGELOG: readonly ChangelogRelease[] = ${JSON.stringify(releases, null, 2)};\n`
  );
}

/** Generates (or, with `check`, verifies) the module; returns true when the file is up to date afterwards. */
export function generate({ check = false, changelog = CHANGELOG_PATH, output = OUTPUT_PATH } = {}) {
  let source = '';
  try {
    source = readFileSync(changelog, 'utf8');
  } catch {
    // No changelog: an empty panel, never a failed build.
  }
  const text = render(parseChangelog(source));
  let current = null;
  try {
    current = readFileSync(output, 'utf8');
  } catch {
    // Missing: written below.
  }
  if (current === text) return true;
  if (check) return false;
  mkdirSync(dirname(output), { recursive: true });
  writeFileSync(output, text);
  return true;
}

/* c8 ignore start: process entry point */
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check');
  const ok = generate({ check });
  if (!ok) {
    console.error('src/app/whats-new/changelog.generated.ts is stale: run `npm run whats-new`');
    process.exit(1);
  }
}
/* c8 ignore stop */
