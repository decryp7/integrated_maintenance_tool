#!/usr/bin/env node
// Checks commit messages against Conventional Commits (AGENTS.md).
//   node scripts/commit-lint.mjs --file .git/COMMIT_EDITMSG   (commit-msg hook)
//   node scripts/commit-lint.mjs --range origin/main..HEAD    (CI, pull requests; merge commits are not checked)
// Exits 1 with one line per bad message.

import { execFileSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';

export const TYPES = ['feat', 'fix', 'perf', 'refactor', 'test', 'docs', 'ci', 'chore', 'build', 'style', 'revert'];
const HEADER = new RegExp(`^(${TYPES.join('|')})(\\([a-z0-9][a-z0-9._/-]*\\))?!?: \\S.*$`);
const MAX_HEADER = 200;
// Paddock rule 8: no co-author trailers and no AI attribution anywhere in a message.
const ATTRIBUTION = [
  [/^\s*co-authored-by:/im, 'a "Co-Authored-By" trailer'],
  [/generated (with|by) .*(claude|anthropic|chatgpt|openai|copilot|gemini)/i, 'an AI "generated with/by" line'],
  [/🤖/u, 'the robot-emoji attribution marker'],
  [/\b(claude|anthropic)\b.*<[^>]*@[^>]*>/i, 'an AI author/trailer e-mail'],
];

/** Problems with one message (empty when it is fine). Merge, fixup and revert commits generated by git pass. */
export function lint(message) {
  const lines = message.replace(/\r\n/g, '\n').split('\n').filter((l) => !l.startsWith('#'));
  const header = (lines[0] ?? '').trim();
  if (/^(Merge|Revert|fixup!|squash!|amend!) /.test(header)) return [];
  const problems = [];
  if (!header) problems.push('the message is empty');
  else if (!HEADER.test(header)) problems.push(`"${header}" does not start with "<type>(<scope>)?: <subject>"; types: ${TYPES.join(', ')}`);
  if (header.length > MAX_HEADER) problems.push(`the first line is ${header.length} characters (at most ${MAX_HEADER})`);
  if (lines.length > 1 && lines[1].trim() !== '') problems.push('the second line must be empty');
  for (const [re, what] of ATTRIBUTION) if (re.test(lines.join('\n'))) problems.push(`the message carries ${what}: no co-author or AI attribution (AGENTS.md rule 8)`);
  return problems;
}

function messagesInRange(range) {
  const out = execFileSync('git', ['log', '--no-merges', '--format=%H%x00%B%x01', range], { encoding: 'utf8' });
  return out
    .split('\x01')
    .map((s) => s.trim())
    .filter(Boolean)
    .map((s) => {
      const [sha, body] = s.split('\x00');
      return { id: sha.slice(0, 10), message: body ?? '' };
    });
}

function main(argv) {
  const [flag, value] = argv;
  let items;
  if (flag === '--file' && value) items = [{ id: value, message: readFileSync(value, 'utf8') }];
  else if (flag === '--range' && value) items = messagesInRange(value);
  else {
    console.error('usage: commit-lint.mjs --file <path> | --range <rev-range>');
    return 2;
  }
  let bad = 0;
  for (const { id, message } of items) {
    for (const p of lint(message)) {
      console.error(`${id}: ${p}`);
      bad++;
    }
  }
  return bad ? 1 : 0;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) process.exit(main(process.argv.slice(2)));
